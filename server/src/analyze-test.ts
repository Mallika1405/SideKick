import './env.js';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { snapshot } from './shadow.js';
import { Project, buildDetail } from './analyze.js';
const root = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..', 'demo-repo');
snapshot(root);
const proj = new Project(root);
const ctx = { root, graph: { nodes: [{ key: 'cleaning', label: 'Data Cleaning', kind: 'module' as const, summary: '', files: [...proj.files.keys()].filter((f) => f.includes('cleaning/')) }], edges: [] }, changed: new Map() };
const show = (t: Parameters<typeof buildDetail>[1]) => { const d = buildDetail(proj, t, ctx, 'click')!; console.log(`\n== ${JSON.stringify(t)}\n nodes: ${d.nodes.map((n) => `${n.kind}:${n.label}`).join(' | ')}\n edges: ${d.edges.map((e) => `${e.from.split(/[:#]/).pop()}-${e.label}->${e.to.split(/[:#]/).pop()}`).join(', ')}`); };
show({ level: 'component', key: 'cleaning' });
show({ level: 'file', file: 'sleepstudy/pipeline.py' });
show({ level: 'file', file: 'sleepstudy/cleaning/pipeline.py' });
show({ level: 'function', file: 'sleepstudy/pipeline.py', fn: 'run' });
show({ level: 'function', file: 'sleepstudy/cleaning/missing.py', fn: 'missing' });
